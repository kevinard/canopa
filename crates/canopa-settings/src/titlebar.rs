//! Compositor window chrome that follows the shared appearance.
//!
//! Settings generates `niri-appearance.kdl` from the `appearance` block of
//! `config.kdl` at session start and after Personalization saves. Niri reads
//! the user's overrides in `niri-custom.kdl` after this file.
use crate::{
    session::Paths,
    storage::{Snapshot, quote},
};
use anyhow::Result;
use canopa_theme::{Appearance, ColorScheme, Rgb};
use std::path::Path;

/// The generated include. Settings replaces it.
pub const GENERATED: &str = "niri-appearance.kdl";

const HEADER: &str = "// Generated by Canopa Settings from `appearance` in config.kdl; Settings replaces this file.\n// Put your own compositor options in niri-custom.kdl.\n";

/// The include line Settings adds to `niri.kdl`, and the line it goes before.
const INCLUDE: &str = "include \"niri-appearance.kdl\"";
const CUSTOM_INCLUDE: &str = "include \"niri-custom.kdl\"";

/// The file `Paths::initialize` creates before the first refresh, so `niri.kdl`
/// stays valid even if generating fails.
pub fn placeholder() -> &'static str {
    HEADER
}

fn hex(Rgb(r, g, b): Rgb) -> String {
    format!("#{r:02x}{g:02x}{b:02x}")
}

fn hex_alpha(Rgb(r, g, b): Rgb, alpha: u8) -> String {
    format!("#{r:02x}{g:02x}{b:02x}{alpha:02x}")
}

fn mix(base: Rgb, tint: Rgb, amount: u16) -> Rgb {
    let channel = |base, tint| {
        ((u16::from(base) * (100 - amount) + u16::from(tint) * amount + 50) / 100) as u8
    };
    Rgb(
        channel(base.0, tint.0),
        channel(base.1, tint.1),
        channel(base.2, tint.2),
    )
}

fn font_size(appearance: &Appearance) -> u32 {
    let size = appearance.typography().body_size.px();
    // Configuration has already applied text-scale to the resolved body size.
    // Niri caps the titlebar height at 64 logical pixels. Leave room for the
    // line height of fallback fonts and the space above and below the title.
    size.round().clamp(1., 36.) as u32
}

/// A Pango font description: the appearance families in order, at the body
/// size scaled by the text scale.
fn font(appearance: &Appearance, size: u32) -> String {
    let typography = appearance.typography();
    // Pango separates families with commas; a name containing one cannot be listed.
    let families: Vec<&str> = typography
        .family
        .iter()
        .map(|family| family.trim())
        .filter(|family| !family.is_empty() && !family.contains(',') && !family.contains('\n'))
        .collect();
    let families = if families.is_empty() {
        "sans-serif".to_owned()
    } else {
        families.join(", ")
    };
    format!("{families} Medium {size}px")
}

/// The generated include for `appearance`.
pub fn text(appearance: &Appearance) -> String {
    let palette = appearance.palette();
    let size = font_size(appearance);
    let height = (size + 26).max(40);
    let high_contrast = appearance.high_contrast();
    let light = appearance.color_scheme == ColorScheme::Light;
    let (shadow, tile_shadow, inactive_tile_shadow, floating_shadow, inactive_floating_shadow) =
        match appearance.color_scheme {
            ColorScheme::Dark => (Rgb(0, 0, 0), 0x80, 0x4d, 0xb0, 0x80),
            ColorScheme::Light => (palette.text, 0x60, 0x3a, 0x54, 0x38),
        };
    let (floating_softness, floating_spread, floating_offset) =
        if light { (42, 2, 12) } else { (52, 6, 18) };
    let (active, inactive, muted, leading, trailing, rim) = if high_contrast {
        (
            palette.surface,
            palette.background,
            palette.text,
            palette.accent,
            palette.accent,
            hex(palette.border),
        )
    } else {
        (
            mix(palette.surface, palette.accent, if light { 20 } else { 10 }),
            mix(palette.background, palette.surface, 60),
            palette.muted,
            mix(palette.surface, palette.accent, if light { 98 } else { 88 }),
            mix(palette.surface, palette.accent, if light { 88 } else { 48 }),
            hex_alpha(palette.border, 0x99),
        )
    };
    format!(
        "{HEADER}layout {{
    background-color \"{workspace}\"
    titlebar {{
        height {height}
        font {font}
        active-color \"{active}\"
        inactive-color \"{inactive}\"
        text-color \"{text}\"
        inactive-text-color \"{muted}\"
        button-hover-color \"{hover}\"
        close-hover-color \"{close}\"
    }}
    border {{
        active-color \"{accent}\"
        active-gradient from=\"{leading}\" to=\"{trailing}\" angle=155
        inactive-color \"{rim}\"
        urgent-color \"{urgent}\"
    }}
    shadow {{ color \"{tile_shadow}\"; inactive-color \"{inactive_tile_shadow}\"; }}
    insert-hint {{ color \"{insert}\"; }}
}}
window-rule {{
    match is-floating=true
    shadow {{ softness {floating_softness}; spread {floating_spread}; offset x=0 y={floating_offset}; color \"{floating_shadow}\"; inactive-color \"{inactive_floating_shadow}\"; }}
}}
overview {{ backdrop-color \"{backdrop}\"; }}
",
        workspace = hex_alpha(palette.background, 0x42),
        backdrop = hex(palette.background),
        font = quote(&font(appearance, size)),
        active = hex(active),
        inactive = hex(inactive),
        text = hex(palette.text),
        muted = hex(muted),
        hover = hex_alpha(palette.text, 0x26),
        close = hex(palette.danger),
        accent = hex(palette.accent),
        leading = hex(leading),
        trailing = hex(trailing),
        urgent = hex(palette.warning),
        insert = hex_alpha(palette.accent, 0x5c),
        tile_shadow = hex_alpha(shadow, tile_shadow),
        inactive_tile_shadow = hex_alpha(shadow, inactive_tile_shadow),
        floating_shadow = hex_alpha(shadow, floating_shadow),
        inactive_floating_shadow = hex_alpha(shadow, inactive_floating_shadow),
    )
}

/// `niri.kdl` with the generated include added before `niri-custom.kdl`, or
/// `None` when it is already included or the person removed that anchor.
fn with_include(text: &str) -> Option<String> {
    let lines = || text.lines().map(str::trim);
    if lines().any(|line| line == INCLUDE) {
        return None;
    }
    let mut offset = 0;
    for line in text.split_inclusive('\n') {
        if line.trim() == CUSTOM_INCLUDE {
            return Some(format!("{}{INCLUDE}\n{}", &text[..offset], &text[offset..]));
        }
        offset += line.len();
    }
    None
}

/// Writes the include for `appearance` and adds it to `niri.kdl` when missing.
/// Each candidate is validated before it replaces a file. Returns whether a
/// file changed, so the caller knows to reload the compositor.
pub fn refresh(
    paths: &Paths,
    appearance: &Appearance,
    validate: impl Fn(&Path) -> Result<()>,
) -> Result<bool> {
    let mut changed = false;
    let generated = Snapshot::load(paths.titlebar_appearance())?;
    let text = text(appearance);
    if generated.text != text {
        // The include is a complete Niri configuration on its own.
        generated.save(&text, &validate)?;
        changed = true;
    }
    let niri = Snapshot::load(paths.niri())?;
    if let Some(text) = with_include(&niri.text) {
        niri.save(&text, &validate)?;
        changed = true;
    }
    Ok(changed)
}

/// The appearance in `config.kdl`, or the defaults when it has none.
pub fn appearance(paths: &Paths) -> Result<Appearance> {
    let snapshot = Snapshot::load(paths.common())?;
    Ok(crate::preferences::Personal::load(&snapshot)?.appearance)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_dark_defaults_match_the_shipped_compositor_defaults() {
        let generated = text(&Appearance::default());
        let defaults = include_str!("../../../packaging/niri/defaults.kdl");
        for line in generated
            .lines()
            .filter(|line| line.starts_with("    background-color") || line.starts_with("        "))
            .map(str::trim)
        {
            assert!(defaults.contains(line), "{line}");
        }
    }

    #[test]
    fn light_appearance_and_text_scale_follow() {
        use canopa_config::{Component, Document, Format};
        let appearance = Document::parse(
            "schema-version 1\nappearance { color-scheme \"light\"; text-scale 150; }\n".into(),
            None,
            Format::CanopaV1,
            Component::Lockscreen,
            "",
        )
        .unwrap()
        .appearance();
        let generated = text(&appearance);
        assert!(generated.contains("active-color \"#d0dfd5\""));
        assert!(generated.contains("text-color \"#20342c\""));
        assert!(generated.contains("button-hover-color \"#20342c26\""));
        assert!(generated.contains("font \"Inter, sans-serif Medium 21px\""));
        assert!(generated.contains("height 47"));
        assert!(generated.contains("backdrop-color \"#e3eae6\""));
        let gradient = generated
            .lines()
            .find(|line| line.contains("active-gradient"))
            .unwrap();
        let active_titlebar = Rgb::parse_hex("#d0dfd5").unwrap();
        for swatch in gradient.split('"').filter_map(Rgb::parse_hex) {
            assert!(swatch.contrast(active_titlebar) >= 3.);
        }
    }

    #[test]
    fn family_names_are_quoted_and_unlistable_ones_dropped() {
        let mut appearance = Appearance::default();
        std::sync::Arc::make_mut(&mut appearance.customization)
            .typography
            .family = vec!["A \"quoted\" face".into(), "Bad, name".into()];
        let generated = text(&appearance);
        assert!(
            generated.contains(r#"font "A \"quoted\" face Medium 14px""#),
            "{generated}"
        );
        let document = kdl::KdlDocument::parse_v1(&generated).unwrap();
        assert_eq!(document.nodes().len(), 3);
    }

    #[test]
    fn the_include_goes_before_the_custom_include_once() {
        let base = "include \"/usr/share/canopa/niri-defaults.kdl\"\ninclude \"niri-input.kdl\"\ninclude \"niri-displays.kdl\"\ninclude \"niri-custom.kdl\"\n// tail\n";
        let migrated = with_include(base).unwrap();
        assert_eq!(
            migrated,
            "include \"/usr/share/canopa/niri-defaults.kdl\"\ninclude \"niri-input.kdl\"\ninclude \"niri-displays.kdl\"\ninclude \"niri-appearance.kdl\"\ninclude \"niri-custom.kdl\"\n// tail\n"
        );
        assert_eq!(with_include(&migrated), None);
        // Without the anchor the person's structure is left alone.
        assert_eq!(with_include("include \"other.kdl\"\n"), None);
    }
}
