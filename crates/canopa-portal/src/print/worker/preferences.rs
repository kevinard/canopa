//! Application hints choose only current advertised values. They never approve a
//! printer option, printable area, file path or prepared-document transformation.
use super::{
    Capabilities, CustomSize, JobOptions, SettingField as Field, Sides, settings::Resolution,
};
use crate::print::{PageSetup, SettingsHints};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

const KEYS: &[&str] = &[
    "default-source",
    "media-source",
    "cups-InputSlot",
    "media-type",
    "cups-MediaType",
    "quality",
    "print-quality",
    "cups-cupsPrintQuality",
    "resolution",
    "resolution-x",
    "resolution-y",
    "printer-resolution",
    "canopa-printer-resolution",
    "cups-Resolution",
    "duplex",
    "sides",
    "cups-Duplex",
    "use-color",
    "print-color-mode",
    "cups-ColorModel",
    "paper-format",
    "media",
    "cups-PageSize",
    "paper-width",
    "paper-height",
];

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Preferences {
    values: BTreeMap<String, String>,
    page_setup: PageSetup,
}
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PreferenceSelection {
    pub options: JobOptions,
    pub custom_size: Option<CustomSize>,
    pub unavailable: bool,
}
type PaperChoice = (Option<String>, Option<CustomSize>);
impl Preferences {
    pub fn new(settings: &SettingsHints, page_setup: &PageSetup) -> Self {
        Self {
            values: KEYS
                .iter()
                .filter_map(|k| settings.advisory(k).map(|v| ((*k).into(), v.into())))
                .collect(),
            page_setup: page_setup.clone(),
        }
    }
    pub(super) fn validate(&self) -> anyhow::Result<()> {
        self.page_setup.validate()?;
        anyhow::ensure!(
            self.values.len() <= KEYS.len()
                && self.values.iter().all(|(k, v)| KEYS.contains(&k.as_str())
                    && v.len() <= 4096
                    && !v.contains('\0')),
            "Invalid print preferences"
        );
        Ok(())
    }
    pub(super) fn paper_names(&self) -> impl Iterator<Item = &str> {
        [
            self.page_setup.name.as_deref(),
            self.page_setup.ppd_name.as_deref(),
            self.get("paper-format"),
            self.get("media"),
            self.get("cups-PageSize"),
        ]
        .into_iter()
        .flatten()
    }
    fn get(&self, key: &str) -> Option<&str> {
        self.values.get(key).map(String::as_str)
    }

    /// Aliases are generated by the selected queue's bounded public CUPS/PPD
    /// adapter. Display labels and arbitrary application options are never used.
    pub(super) fn resolve(
        &self,
        caps: &Capabilities,
        aliases: &[(Field, String, String)],
        paper_aliases: &[(String, String)],
    ) -> PreferenceSelection {
        let mut result = PreferenceSelection {
            options: JobOptions {
                media: caps.default_media.clone(),
                custom_media: None,
                sides: caps.default_sides,
                color: caps.default_color,
                settings: caps.controls.defaults(),
                ..Default::default()
            },
            custom_size: caps
                .default_custom_media
                .as_ref()
                .and_then(|m| CustomSize::from_media(m).ok()),
            unavailable: false,
        };
        for (field, keys) in [
            (
                Field::Source,
                &["default-source", "media-source", "cups-InputSlot"][..],
            ),
            (Field::Type, &["media-type", "cups-MediaType"][..]),
            (
                Field::Quality,
                &["quality", "print-quality", "cups-cupsPrintQuality"][..],
            ),
        ] {
            let resolved = agree(
                keys.iter().filter_map(|k| self.get(k).map(|v| (*k, v))),
                |(key, value)| {
                    let quality = match (key, value) {
                        ("quality", "draft" | "low") => "3",
                        ("quality", "normal") => "4",
                        ("quality", "high") => "5",
                        _ => value,
                    };
                    unique(
                        caps.controls
                            .get(field)
                            .choices
                            .iter()
                            .filter(|c| {
                                field.equivalent(&c.value, quality)
                                    || aliases.iter().any(|(f, canonical, alias)| {
                                        *f == field
                                            && canonical == &c.value
                                            && alias.eq_ignore_ascii_case(quality)
                                    })
                            })
                            .map(|c| c.value.clone()),
                    )
                },
            );
            match resolved {
                Ok(Some(v)) => result.options.settings.set(field, Some(v)),
                Err(()) => result.unavailable = true,
                _ => {}
            }
        }
        match self.resolution(caps, aliases) {
            Ok(Some(v)) => result.options.settings.resolution = Some(v),
            Err(()) => result.unavailable = true,
            _ => {}
        }
        let sides = agree(
            ["duplex", "sides", "cups-Duplex"]
                .into_iter()
                .filter_map(|k| self.get(k)),
            |v| {
                match v {
                    "simplex" | "one-sided" | "None" => Some(Sides::OneSided),
                    "vertical" | "two-sided-long-edge" | "DuplexNoTumble" => Some(Sides::LongEdge),
                    "horizontal" | "two-sided-short-edge" | "DuplexTumble" => {
                        Some(Sides::ShortEdge)
                    }
                    _ => None,
                }
                .filter(|v| caps.sides.contains(v))
            },
        );
        match sides {
            Ok(Some(v)) => result.options.sides = Some(v),
            Err(()) => result.unavailable = true,
            _ => {}
        }
        let color = agree(
            ["use-color", "print-color-mode", "cups-ColorModel"]
                .into_iter()
                .filter_map(|k| self.get(k)),
            |v| {
                match v {
                    "true" | "color" | "RGB" | "CMYK" => Some(true),
                    "false" | "monochrome" | "Gray" => Some(false),
                    _ => None,
                }
                .filter(|v| caps.colors.contains(v))
            },
        );
        match color {
            Ok(Some(v)) => result.options.color = Some(v),
            Err(()) => result.unavailable = true,
            _ => {}
        }
        match self.paper(caps, paper_aliases) {
            Ok(Some((media, size))) => {
                result.options.media = media;
                result.custom_size = size;
            }
            Err(()) => result.unavailable = true,
            _ => {}
        }
        result
    }
    fn resolution(
        &self,
        caps: &Capabilities,
        aliases: &[(Field, String, String)],
    ) -> Result<Option<String>, ()> {
        let explicit = agree(
            [
                "printer-resolution",
                "canopa-printer-resolution",
                "cups-Resolution",
            ]
            .into_iter()
            .filter_map(|k| self.get(k)),
            |value| {
                unique(
                    caps.controls
                        .resolution
                        .choices
                        .iter()
                        .filter(|c| {
                            Field::Resolution.equivalent(&c.value, value)
                                || aliases.iter().any(|(f, canonical, alias)| {
                                    *f == Field::Resolution
                                        && canonical == &c.value
                                        && alias == value
                                })
                        })
                        .map(|c| c.value.clone()),
                )
            },
        )?;
        let number = |v: &str| -> Result<u32, ()> {
            if v.is_empty() || v.len() > 7 || !v.bytes().all(|b| b.is_ascii_digit()) {
                return Err(());
            }
            v.parse::<u32>()
                .ok()
                .filter(|v| (1..=1_000_000).contains(v))
                .ok_or(())
        };
        let base = self.get("resolution").map(number).transpose()?;
        let x = self.get("resolution-x").map(number).transpose()?;
        let y = self.get("resolution-y").map(number).transpose()?;
        let dpi = match (base, x, y) {
            (None, None, None) => None,
            (base, x, y) => {
                let x = x.or(base).ok_or(())?;
                let y = y.or(base).ok_or(())?;
                if base.is_some_and(|base| base != x) {
                    return Err(());
                }
                Some((x, y))
            }
        };
        if let Some(value) = explicit {
            if dpi.is_some_and(|dpi| Resolution::parse(&value).map(|r| r.dpi()).ok() != Some(dpi)) {
                return Err(());
            }
            return Ok(Some(value));
        }
        dpi.map(|(x, y)| {
            unique(
                caps.controls
                    .resolution
                    .choices
                    .iter()
                    .filter(|c| {
                        Resolution::parse(&c.value).is_ok_and(|r| !r.dpcm && (r.x, r.y) == (x, y))
                    })
                    .map(|c| c.value.clone()),
            )
            .ok_or(())
        })
        .transpose()
    }
    fn paper(
        &self,
        caps: &Capabilities,
        aliases: &[(String, String)],
    ) -> Result<Option<PaperChoice>, ()> {
        let names = self.paper_names().collect::<Vec<_>>();
        let custom = |name: &str| {
            name.starts_with("custom_")
                || name.starts_with("custom-")
                || name.starts_with("Custom.")
                || name == "canopa-custom"
        };
        let fixed = agree(names.iter().copied().filter(|n| !custom(n)), |name| {
            unique(
                caps.media
                    .iter()
                    .filter(|m| {
                        m.id == name
                            || (name.contains('_')
                                && m.id
                                    .strip_prefix(name)
                                    .is_some_and(|tail| tail.starts_with('_')))
                            || aliases
                                .iter()
                                .any(|(alias, id)| alias == name && id == &m.id)
                    })
                    .map(|m| m.id.clone()),
            )
        })?;
        let dimension = |v: f64| -> Result<u32, ()> {
            let units = v * 100.;
            if !units.is_finite()
                || !(1. ..=1_000_000.).contains(&units)
                || (units - units.round()).abs() > 0.000001
            {
                return Err(());
            }
            Ok(units.round() as u32)
        };
        let setup = self
            .page_setup
            .width
            .zip(self.page_setup.height)
            .map(|(w, h)| -> Result<CustomSize, ()> {
                Ok(CustomSize {
                    width: dimension(w)?,
                    height: dimension(h)?,
                })
            })
            .transpose()?;
        let strings = match (self.get("paper-width"), self.get("paper-height")) {
            (None, None) => None,
            (Some(w), Some(h)) => Some(CustomSize::parse(w, h).map_err(|_| ())?),
            _ => return Err(()),
        };
        if setup.zip(strings).is_some_and(|(a, b)| a != b) {
            return Err(());
        }
        let size = setup.or(strings);
        if let Some(id) = fixed {
            if names.iter().any(|n| custom(n))
                || size.is_some_and(|s| {
                    caps.media
                        .iter()
                        .find(|m| m.id == id)
                        .and_then(|m| CustomSize::from_media(m).ok())
                        != Some(s)
                })
            {
                return Err(());
            }
            return Ok(Some((Some(id), None)));
        }
        if let Some(size) = size {
            // Dimension-only hints may select exactly one advertised fixed sheet.
            // A named custom sheet remains custom even if dimensions coincide.
            if names.is_empty()
                && let Some(id) = unique(
                    caps.media
                        .iter()
                        .filter(|m| CustomSize::from_media(m).ok() == Some(size))
                        .map(|m| m.id.clone()),
                )
            {
                return Ok(Some((Some(id), None)));
            }
            if caps.custom_media {
                return Ok(Some((None, Some(size))));
            }
            return Err(());
        }
        if names.is_empty() { Ok(None) } else { Err(()) }
    }
}
fn unique<T: PartialEq>(values: impl Iterator<Item = T>) -> Option<T> {
    let mut unique = None;
    for value in values {
        if unique.as_ref().is_some_and(|v| v != &value) {
            return None;
        }
        unique = Some(value);
    }
    unique
}
fn agree<T: PartialEq, I>(
    values: impl Iterator<Item = I>,
    resolve: impl Fn(I) -> Option<T>,
) -> Result<Option<T>, ()> {
    let mut result = None;
    for value in values {
        let value = resolve(value).ok_or(())?;
        if result.as_ref().is_some_and(|v| v != &value) {
            return Err(());
        }
        result = Some(value);
    }
    Ok(result)
}

